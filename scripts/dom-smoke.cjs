/* Optional interaction smoke test. No browser or network is used by this test.
 * Install jsdom separately, or point ATLAS_JSDOM at an existing installation. */
const {JSDOM} = require(process.env.ATLAS_JSDOM || 'jsdom');
const {readFileSync} = require('node:fs');
const {resolve} = require('node:path');
const assert = require('node:assert/strict');
const root = resolve(__dirname,'../dist');
const dom = new JSDOM(readFileSync(resolve(root,'index.html'),'utf8'),{url:process.env.ATLAS_TEST_URL || 'https://atlas.example/',runScripts:'outside-only'});
const w=dom.window, d=w.document, downloads=[];
const domErrors=[];
dom.virtualConsole.on('jsdomError',error=>domErrors.push(error));
let copied='',blob;
w.scrollTo=()=>{};
w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
Object.defineProperty(w.navigator,'clipboard',{value:{writeText:async value=>{copied=value;}}});
w.Blob=globalThis.Blob;
w.URL.createObjectURL=value=>{blob=value;return 'blob:test-download';};
w.URL.revokeObjectURL=()=>{};
const click=w.HTMLAnchorElement.prototype.click;
w.HTMLAnchorElement.prototype.click=function(){if(this.download){downloads.push(this.download);return;}click.call(this);};
for(const script of ['data/catalog.js','core.js','app.js'])w.eval(readFileSync(resolve(root,script),'utf8'));
const data=w.ATLAS_DATA;
const $=s=>d.querySelector(s);
const $$=s=>[...d.querySelectorAll(s)];
const rows=()=>$$('.result-row');
const input=(selector,value)=>{const el=$(selector);el.value=value;el.dispatchEvent(new w.Event('input',{bubbles:true}));};
const change=(selector,value)=>{const el=$(selector);if(el.type==='checkbox')el.checked=value;else el.value=value;el.dispatchEvent(new w.Event('change',{bubbles:true}));};
const reset=()=>$('#reset').click();

(async()=>{
  assert.equal(rows().length,data.results.length,'all bounds render');
  assert.equal($('.group-symbol').textContent,'O(1)','constant rounds are first');
  assert.ok(!$('#results-body').textContent.includes('undefined'),'no missing data printed');
  $('[data-round="logstar"]').click();
  assert.equal(rows().length,data.results.filter(r=>r.roundClass==='logstar').length);
  assert.ok(w.location.hash.includes('round=logstar'),'filters are shareable');
  reset();
  change('#model','LOCAL');
  assert.equal(rows().length,data.results.filter(r=>r.model==='LOCAL').length);
  change('#transfer',true);
  assert.equal(rows().length,data.results.filter(r=>r.model==='LOCAL'||(r.bound==='upper'&&['CONGEST','Anonymous'].includes(r.model))).length);
  reset();
  input('#search','Picavet');
  assert.ok(rows().length>0,'author search returns records');
  input('#search','nonexistent-impossible-query');
  assert.equal(rows().length,0);
  assert.equal($('#empty').hidden,false);
  $('#empty-reset').click();
  assert.equal(rows().length,data.results.length);
  const flagged=data.results.find(r=>r.caveat);
  $('[data-result="'+flagged.id+'"]').click();
  assert.equal($('#detail-dialog').open,true);
  assert.ok($('.source-caveat').textContent.includes(flagged.caveat));
  assert.ok(w.location.hash.includes('result='+flagged.id));
  $('[data-bib]').click();
  await Promise.resolve();
  assert.ok(copied.startsWith('@misc{'));
  assert.ok(copied.includes(' and '));
  $('#dialog-close').click();
  assert.equal($('#detail-dialog').open,false);
  assert.ok(!w.location.hash.includes('result='));
  const boxes=$$('[data-select]');
  for(const box of boxes.slice(0,2)){box.checked=true;box.dispatchEvent(new w.Event('change',{bubbles:true}));}
  assert.equal($('#compare-open').disabled,false);
  $('#compare-open').click();
  assert.equal($$('.compare-table thead th').length,3);
  assert.ok($('.compare-table').textContent.includes('Parameters'));
  $('#dialog-close').click();$('#compare-clear').click();
  assert.equal($('#compare-bar').hidden,true);
  $('[data-view="explorer"]').click();
  assert.equal($('#explorer-view').hidden,false);
  const cell=$('[data-matrix-problem]'), count=Number(cell.textContent);
  cell.click();
  assert.equal($('#catalog-view').hidden,false);
  assert.equal(rows().length,count,'matrix drill-down exactly matches cell count');
  $('[data-view="bibliography"]').click();
  assert.equal($$('.paper-entry').length,data.papers.length);
  input('#bib-search','Picavet');
  assert.ok($$('.paper-entry').length>0);
  assert.ok($$('.paper-entry').length<data.papers.length);
  const paperButton=$('[data-paper-results]'), paperId=paperButton.dataset.paperResults;
  paperButton.click();
  assert.equal(rows().length,data.results.filter(r=>r.paperId===paperId).length,'bibliography drill-down uses exact paper ID');
  $('#export').click();
  assert.equal(downloads.at(-1),'distributed-approximation-results.csv');
  const csv=await blob.text();
  assert.ok(csv.includes('caveatUrl'));
  assert.ok(csv.includes('paperTitle'));
  assert.ok(csv.includes(paperId));
  $('[data-view="about"]').click();
  assert.equal($('#about-view').hidden,false);
  assert.ok($('#about-view').textContent.includes('not exhaustive'));
  assert.equal(domErrors.length,0,'no uncaught DOM errors');
  console.log('DOM smoke checks passed: rendering, model implications, filters, empty state, source caveats, citations, comparison, explorer, bibliography, exports and navigation.');
  w.close();
})().catch(error=>{console.error(error);w.close();process.exitCode=1;});
