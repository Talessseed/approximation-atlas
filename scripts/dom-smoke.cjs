function assertProblemRegions(state={},label='problem regions'){
  const expected=Array.from(w.AtlasCore.filtered(data.results,testPapers,state));
  const rendered=rows();
  assert.deepEqual(rendered.map(tr=>tr.querySelector('.problem-button').dataset.result),expected.map(result=>result.id),label+': grouping preserves the exact filtered order');
  const groups=[];
  expected.forEach((result,index)=>{
    const previous=expected[index-1];
    if(!previous||previous.problem!==result.problem||((state.sort||'rounds')==='rounds'&&previous.roundClass!==result.roundClass))groups.push({start:index,problem:result.problem,count:0});
    groups.at(-1).count++;
  });
  assert.equal($$('#results-body .problem-region-marker').length,groups.length,label+': each contiguous run has one bracket marker');
  assert.equal($$('#results-body .problem-region-start').length,groups.length,label+': each run has one start');
  assert.equal($$('#results-body .problem-region-end').length,groups.length,label+': each run has one end');
  const tokens=new Set();
  groups.forEach(group=>{
    const first=rendered[group.start],marker=first.querySelector('.problem-region-marker');
    assert.ok(marker,label+': the marker belongs to the first row');
    assert.equal(first.firstElementChild,marker,label+': the marker is in the left gutter');
    assert.equal(marker.rowSpan,group.count,label+': the marker spans exactly its contiguous run');
    assert.equal(marker.getAttribute('aria-hidden'),'true',label+': the visual bracket is decorative');
    assert.equal(marker.dataset.regionProblem,group.problem,label+': the marker identifies its actual problem');
    assert.ok(marker.querySelector('.problem-region-bracket'),label+': the marker contains the bracket ornament');
    assert.equal(marker.querySelector('button,a,input,select,textarea'),null,label+': the gutter adds no interactive tab stop');
    const token=first.dataset.problemRegion;
    assert.match(token,/^problem-region-\d+$/,label+': the region has a stable run token');
    assert.equal(tokens.has(token),false,label+': separate runs have distinct tokens');
    tokens.add(token);
    let physical=first;
    for(let offset=0;offset<group.count;offset++){
      const tr=rendered[group.start+offset],result=expected[group.start+offset];
      assert.equal(physical,tr,label+': a bracket never crosses a round header or separator');
      assert.equal(tr.dataset.problemRegion,token,label+': every adjacent row stays in its own region');
      assert.equal(tr.dataset.regionProblem,group.problem,label+': row metadata keeps exact problem labels');
      assert.equal(tr.classList.contains('problem-region-start'),offset===0,label+': only the first row starts the region');
      assert.equal(tr.classList.contains('problem-region-end'),offset===group.count-1,label+': only the last row ends the region');
      assert.equal(tr.querySelectorAll('.problem-region-marker').length,offset===0?1:0,label+': later rows use the real rowspan');
      assert.equal(tr.children.length,offset===0?8:7,label+': the seven original data columns stay intact');
      assert.equal(tr.querySelector('[data-select]').dataset.select,result.id,label+': selection stays attached to its result');
      assert.equal(tr.querySelector('.cite-button').dataset.cite,result.paperId,label+': citations stay attached to their source');
      assert.ok(tr.querySelector('.approx-cell [data-tex]'),label+': the approximation keeps its MathJax expression');
      assert.ok(tr.querySelector('.round-cell .round-bound'),label+': the round bound remains rendered');
      physical=physical.nextElementSibling;
    }
  });
  for(const heading of $$('#results-body .group-row > td'))assert.equal(heading.colSpan,8,label+': regime headings span the gutter and all data columns');
  const header=$('.results-table thead .problem-region-col');
  assert.ok(header,label+': the table reserves a matching gutter header');
  assert.equal(header.getAttribute('aria-hidden'),'true',label+': the decorative header is hidden from assistive technology');
  if((state.sort||'rounds')!=='rounds')assert.equal($$('#results-body .group-row').length,0,label+': other sorts have no stale regime headers');
  return groups;
}

